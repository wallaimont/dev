-- V1__Initial_Schema.sql
-- SIGA Seguros - Schema completo

-- Usuarios
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ultimo_acesso TIMESTAMP,
    senha_temporaria BOOLEAN DEFAULT FALSE,
    tentativas_login INT DEFAULT 0,
    bloqueado_ate TIMESTAMP,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200)
);

-- Clientes
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_pessoa VARCHAR(2) NOT NULL,
    nome VARCHAR(150),
    razao_social VARCHAR(200),
    nome_fantasia VARCHAR(200),
    cpf VARCHAR(14) UNIQUE,
    cnpj VARCHAR(18) UNIQUE,
    rg VARCHAR(20),
    inscricao_estadual VARCHAR(30),
    data_nascimento DATE,
    data_fundacao DATE,
    telefone VARCHAR(20),
    celular VARCHAR(20),
    email VARCHAR(200),
    cep VARCHAR(10),
    logradouro VARCHAR(200),
    numero VARCHAR(10),
    complemento VARCHAR(100),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    estado VARCHAR(2),
    observacoes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200)
);

-- Seguradoras
CREATE TABLE seguradoras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    codigo_interno VARCHAR(20),
    telefone VARCHAR(20),
    email VARCHAR(200),
    contato_comercial VARCHAR(150),
    percentual_comissao_padrao DECIMAL(5,2),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200)
);

-- Corretoras
CREATE TABLE corretoras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    responsavel VARCHAR(150),
    telefone VARCHAR(20),
    email VARCHAR(200),
    percentual_comissao DECIMAL(5,2),
    observacoes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200)
);

-- Ramos de Seguro
CREATE TABLE ramos_seguro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200)
);

-- Propostas
CREATE TABLE propostas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_proposta VARCHAR(30) NOT NULL UNIQUE,
    cliente_id BIGINT NOT NULL,
    seguradora_id BIGINT NOT NULL,
    corretora_id BIGINT,
    ramo_seguro_id BIGINT NOT NULL,
    vigencia_inicial DATE,
    vigencia_final DATE,
    premio_liquido DECIMAL(15,2),
    premio_total DECIMAL(15,2),
    percentual_comissao DECIMAL(5,2),
    valor_comissao DECIMAL(15,2),
    status VARCHAR(20) NOT NULL,
    observacoes TEXT,
    responsavel_interno VARCHAR(150),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (seguradora_id) REFERENCES seguradoras(id),
    FOREIGN KEY (corretora_id) REFERENCES corretoras(id),
    FOREIGN KEY (ramo_seguro_id) REFERENCES ramos_seguro(id)
);

-- Apolices
CREATE TABLE apolices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_apolice VARCHAR(30) NOT NULL UNIQUE,
    proposta_id BIGINT,
    cliente_id BIGINT NOT NULL,
    seguradora_id BIGINT NOT NULL,
    corretora_id BIGINT,
    ramo_seguro_id BIGINT NOT NULL,
    data_emissao DATE,
    inicio_vigencia DATE NOT NULL,
    fim_vigencia DATE NOT NULL,
    premio_total DECIMAL(15,2),
    percentual_comissao DECIMAL(5,2),
    valor_comissao DECIMAL(15,2),
    forma_pagamento VARCHAR(20),
    quantidade_parcelas INT,
    status VARCHAR(20) NOT NULL,
    observacoes TEXT,
    responsavel_interno VARCHAR(150),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (proposta_id) REFERENCES propostas(id),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (seguradora_id) REFERENCES seguradoras(id),
    FOREIGN KEY (corretora_id) REFERENCES corretoras(id),
    FOREIGN KEY (ramo_seguro_id) REFERENCES ramos_seguro(id)
);

-- Renovacoes
CREATE TABLE renovacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apolice_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    data_vencimento DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    responsavel VARCHAR(150),
    data_ultimo_contato DATE,
    retorno_cliente TEXT,
    observacoes TEXT,
    nova_proposta_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (apolice_id) REFERENCES apolices(id),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (nova_proposta_id) REFERENCES propostas(id)
);

-- Sinistros
CREATE TABLE sinistros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_sinistro VARCHAR(30) NOT NULL UNIQUE,
    apolice_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    seguradora_id BIGINT NOT NULL,
    data_aviso DATE NOT NULL,
    descricao TEXT NOT NULL,
    valor_estimado DECIMAL(15,2),
    valor_pago DECIMAL(15,2),
    status VARCHAR(30) NOT NULL,
    responsavel_interno VARCHAR(150),
    observacoes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (apolice_id) REFERENCES apolices(id),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (seguradora_id) REFERENCES seguradoras(id)
);

-- Lancamentos Financeiros
CREATE TABLE lancamentos_financeiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_lancamento VARCHAR(20) NOT NULL,
    origem VARCHAR(100),
    cliente_id BIGINT,
    corretora_id BIGINT,
    seguradora_id BIGINT,
    proposta_id BIGINT,
    apolice_id BIGINT,
    descricao VARCHAR(500),
    valor DECIMAL(15,2) NOT NULL,
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    forma_pagamento VARCHAR(20),
    status VARCHAR(20) NOT NULL,
    observacoes TEXT,
    numero_parcela INT,
    total_parcelas INT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (corretora_id) REFERENCES corretoras(id),
    FOREIGN KEY (seguradora_id) REFERENCES seguradoras(id),
    FOREIGN KEY (proposta_id) REFERENCES propostas(id),
    FOREIGN KEY (apolice_id) REFERENCES apolices(id)
);

-- Comissoes
CREATE TABLE comissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem VARCHAR(100),
    proposta_id BIGINT,
    apolice_id BIGINT,
    seguradora_id BIGINT,
    corretora_id BIGINT,
    favorecido VARCHAR(200),
    percentual DECIMAL(5,2),
    valor DECIMAL(15,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_prevista DATE,
    data_recebimento DATE,
    observacoes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (proposta_id) REFERENCES propostas(id),
    FOREIGN KEY (apolice_id) REFERENCES apolices(id),
    FOREIGN KEY (seguradora_id) REFERENCES seguradoras(id),
    FOREIGN KEY (corretora_id) REFERENCES corretoras(id)
);

-- Documentos
CREATE TABLE documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo VARCHAR(300) NOT NULL,
    nome_original VARCHAR(300) NOT NULL,
    content_type VARCHAR(100),
    tamanho BIGINT,
    caminho VARCHAR(500) NOT NULL,
    tipo_documento VARCHAR(30),
    cliente_id BIGINT,
    proposta_id BIGINT,
    apolice_id BIGINT,
    sinistro_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(200),
    updated_by VARCHAR(200),
    FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (proposta_id) REFERENCES propostas(id),
    FOREIGN KEY (apolice_id) REFERENCES apolices(id),
    FOREIGN KEY (sinistro_id) REFERENCES sinistros(id)
);

-- Auditoria Logs
CREATE TABLE auditoria_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidade VARCHAR(100) NOT NULL,
    entidade_id BIGINT,
    acao VARCHAR(30) NOT NULL,
    usuario VARCHAR(150),
    data_hora TIMESTAMP NOT NULL,
    dados_anteriores TEXT,
    dados_novos TEXT,
    tela VARCHAR(100),
    ip_address VARCHAR(45)
);

-- Notificacoes
CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    mensagem TEXT NOT NULL,
    tipo VARCHAR(30),
    link VARCHAR(500),
    destinatario VARCHAR(200),
    lida BOOLEAN DEFAULT FALSE,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_leitura TIMESTAMP
);

-- Indices
CREATE INDEX idx_clientes_cpf ON clientes(cpf);
CREATE INDEX idx_clientes_cnpj ON clientes(cnpj);
CREATE INDEX idx_clientes_nome ON clientes(nome);
CREATE INDEX idx_clientes_email ON clientes(email);
CREATE INDEX idx_propostas_numero ON propostas(numero_proposta);
CREATE INDEX idx_propostas_status ON propostas(status);
CREATE INDEX idx_propostas_cliente ON propostas(cliente_id);
CREATE INDEX idx_apolices_numero ON apolices(numero_apolice);
CREATE INDEX idx_apolices_status ON apolices(status);
CREATE INDEX idx_apolices_cliente ON apolices(cliente_id);
CREATE INDEX idx_apolices_vigencia ON apolices(fim_vigencia);
CREATE INDEX idx_sinistros_numero ON sinistros(numero_sinistro);
CREATE INDEX idx_sinistros_status ON sinistros(status);
CREATE INDEX idx_lancamentos_vencimento ON lancamentos_financeiros(vencimento);
CREATE INDEX idx_lancamentos_status ON lancamentos_financeiros(status);
CREATE INDEX idx_comissoes_status ON comissoes(status);
CREATE INDEX idx_auditoria_entidade ON auditoria_logs(entidade, entidade_id);
CREATE INDEX idx_auditoria_usuario ON auditoria_logs(usuario);
CREATE INDEX idx_notificacoes_destinatario ON notificacoes(destinatario, lida);
